import os
import sqlite3
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
DATABASE_PATH = PROJECT_ROOT / "data" / "paper_trading.sqlite3"


class PostgresConnection:
    """Small compatibility wrapper for PostgreSQL connections."""

    def __init__(self, connection):
        self.connection = connection

    def __enter__(self):
        self.connection.__enter__()
        return self

    def __exit__(self, exc_type, exc_value, traceback):
        return self.connection.__exit__(
            exc_type, exc_value, traceback
        )

    def execute(self, query, parameters=()):
        query = query.replace("?", "%s")
        return self.connection.execute(query, parameters)


def get_connection():
    database_url = os.getenv("DATABASE_URL")

    if database_url:
        import psycopg
        from psycopg.rows import dict_row

        connection = psycopg.connect(
            database_url,
            row_factory=dict_row,
        )

        return PostgresConnection(connection)

    DATABASE_PATH.parent.mkdir(parents=True, exist_ok=True)

    connection = sqlite3.connect(DATABASE_PATH)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")

    return connection


def initialize_database():
    database_url = os.getenv("DATABASE_URL")

    if database_url:
        create_table_sql = """
            CREATE TABLE IF NOT EXISTS paper_trades (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                symbol TEXT NOT NULL,
                direction TEXT NOT NULL,
                prediction TEXT NOT NULL,

                candle_timestamp TEXT NOT NULL,
                entry_time TEXT NOT NULL,
                entry_price DOUBLE PRECISION NOT NULL,
                stop_loss DOUBLE PRECISION NOT NULL,
                quantity INTEGER NOT NULL,
                position_value DOUBLE PRECISION NOT NULL,
                estimated_risk DOUBLE PRECISION NOT NULL,

                probabilities TEXT NOT NULL,
                model_version TEXT NOT NULL,

                data_source TEXT NOT NULL,
                synthetic_data INTEGER NOT NULL DEFAULT 0,

                status TEXT NOT NULL DEFAULT 'OPEN',

                exit_price DOUBLE PRECISION,
                exit_time TEXT,
                gross_pnl DOUBLE PRECISION,
                estimated_cost DOUBLE PRECISION,
                net_pnl DOUBLE PRECISION,

                created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                UNIQUE (
                    symbol,
                    candle_timestamp,
                    model_version,
                    direction
                ),

                CHECK (direction IN ('LONG', 'SHORT')),
                CHECK (status IN ('OPEN', 'CLOSED', 'CANCELLED')),
                CHECK (entry_price > 0),
                CHECK (stop_loss > 0),
                CHECK (quantity > 0)
            )
        """
    else:
        create_table_sql = """
            CREATE TABLE IF NOT EXISTS paper_trades (
                id INTEGER PRIMARY KEY AUTOINCREMENT,

                symbol TEXT NOT NULL,
                direction TEXT NOT NULL,
                prediction TEXT NOT NULL,

                candle_timestamp TEXT NOT NULL,
                entry_time TEXT NOT NULL,
                entry_price REAL NOT NULL,
                stop_loss REAL NOT NULL,
                quantity INTEGER NOT NULL,
                position_value REAL NOT NULL,
                estimated_risk REAL NOT NULL,

                probabilities TEXT NOT NULL,
                model_version TEXT NOT NULL,

                data_source TEXT NOT NULL,
                synthetic_data INTEGER NOT NULL DEFAULT 0,

                status TEXT NOT NULL DEFAULT 'OPEN',

                exit_price REAL,
                exit_time TEXT,
                gross_pnl REAL,
                estimated_cost REAL,
                net_pnl REAL,

                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,

                UNIQUE (
                    symbol,
                    candle_timestamp,
                    model_version,
                    direction
                ),

                CHECK (direction IN ('LONG', 'SHORT')),
                CHECK (status IN ('OPEN', 'CLOSED', 'CANCELLED')),
                CHECK (entry_price > 0),
                CHECK (stop_loss > 0),
                CHECK (quantity > 0)
            )
        """

    with get_connection() as connection:
        connection.execute(create_table_sql)


if __name__ == "__main__":
    initialize_database()
    print("MOSAIC 2.0 paper-trading database initialized.")

    if os.getenv("DATABASE_URL"):
        print("Database: PostgreSQL")
    else:
        print(f"Database: SQLite ({DATABASE_PATH})")
